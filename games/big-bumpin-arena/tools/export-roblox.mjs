// Writes roblox/BumpinData.luau from the JS source of truth (config.js + arenas.js), so the Roblox port can never
// drift from the web build's numbers or arena shapes. Run: node games/big-bumpin-arena/tools/export-roblox.mjs
import { writeFileSync } from 'node:fs';
import { CFG, HZ } from '../src/config.js';
import { buildArena, ARENA_ORDER } from '../src/arenas.js';

const key = (k) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : `[${JSON.stringify(k)}]`);
function lua(v, ind = '') {
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'number') return Number.isInteger(v) ? String(v) : String(Math.round(v * 1e4) / 1e4);
  if (typeof v === 'boolean') return String(v);
  if (typeof v === 'string') return JSON.stringify(v);
  if (Array.isArray(v)) { const flat = v.every((x) => typeof x !== 'object' || x === null); return flat ? `{ ${v.map((x) => lua(x)).join(', ')} }` : `{\n${v.map((x) => `${ind}\t${lua(x, ind + '\t')},`).join('\n')}\n${ind}}`; }
  const e = Object.entries(v).filter(([, x]) => x !== undefined && typeof x !== 'function');
  const small = e.every(([, x]) => typeof x !== 'object' || x === null) && e.length <= 14;
  return small ? `{ ${e.map(([k, x]) => `${key(k)} = ${lua(x)}`).join(', ')} }` : `{\n${e.map(([k, x]) => `${ind}\t${key(k)} = ${lua(x, ind + '\t')},`).join('\n')}\n${ind}}`;
}
const arenas = {};
for (const id of ARENA_ORDER) { const a = buildArena(id, CFG.rink.netDepth); arenas[id] = { id: a.id, name: a.name, theme: a.theme, surface: a.surface, w: a.w, h: a.h, cx: a.cx, cy: a.cy, L: a.L, R: a.R, goalHalf: a.goalHalf, netDepth: a.netDepth,
  poly: a.poly, field: a.field, goals: a.goals, bounds: a.bounds, obstacles: a.obstacles.map((o) => ({ kind: o.kind, x: o.x, y: o.y, r: o.r, w: o.w, h: o.h, angle: o.angle })), pits: a.pits, sweepers: a.sweepers.map((s) => ({ x: s.x, y: s.y, len: s.len, speed: s.speed, r: s.r })),
  kick: a.kick, spawns: a.spawns, items: a.items, pads: a.pads, pylons: a.pylons, blockers: a.blockers.map((b) => ({ x: b.x, y: b.y, r: b.r, pit: !!b.pit, soft: !!b.soft })) }; }
const out = `-- GENERATED by tools/export-roblox.mjs from src/config.js and src/arenas.js. Do not edit by hand.\nreturn {\n\tHZ = ${HZ},\n\torder = ${lua(ARENA_ORDER)},\n\tcfg = ${lua(CFG, '\t')},\n\tarenas = ${lua(arenas, '\t')},\n}\n`;
writeFileSync(new URL('../roblox/BumpinData.luau', import.meta.url), out);
console.log(`wrote roblox/BumpinData.luau (${(out.length / 1024).toFixed(1)} KB, ${ARENA_ORDER.length} arenas)`);
