# Writes res/resources.res and src/levels_gen.h (the LevelDef table) from levelmeta.json + the JS level data.
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
M = json.load(open(HERE + '/levelmeta.json')); LJ = json.load(open(HERE + '/../tools/levels.json'))
ROLE = {'purple': 0, 'blue': 0, 'dasher': 0, 'sword': 1, 'star': 1, 'heavy': 2, 'gunner': 2}
NAMES = {1: 'THE BURNING LOBBY'}
BOSSN = {1: 'RAMROD', 15: 'SHREDDER', 16: 'SUPER SHREDDER'}
BHP = {1: 30, 15: 46, 16: 70}
FL_CHARGE, FL_KICK, FL_FIRE = 1, 2, 4
def flags(moves):
    f = 0
    if 'charge' in moves: f |= FL_CHARGE
    if 'kick' in moves: f |= FL_KICK
    if any(m in moves for m in ('throw', 'fire', 'slam')): f |= FL_FIRE
    return f or FL_KICK
res = ['IMAGE title_img "title.png" BEST ALL', 'SPRITE spr_lenny "spr_lenny.png" 10 8 FAST 0', 'SPRITE spr_spin "spr_spin.png" 16 7 FAST 0']
L = []
for n in range(1, 16):
    m = M[str(n)]; rep = m['rep']
    res += [f'PALETTE l{n}_bgpal "l{n}_bg.png"', f'TILESET l{n}_bgt "l{n}_bg.png" BEST ALL', f'MAP l{n}_bgm "l{n}_bg.png" l{n}_bgt BEST 0']
    na = sum(1 for k in rep if k.startswith('arena'))
    for i in range(na):
        res += [f'PALETTE l{n}_ar{i}pal "l{n}_ar{i}.png"', f'TILESET l{n}_ar{i}t "l{n}_ar{i}.png" BEST ALL', f'MAP l{n}_ar{i}m "l{n}_ar{i}.png" l{n}_ar{i}t BEST 0']
    for r in ('light', 'weapon', 'big'): res.append(f'SPRITE l{n}_{r} "l{n}_{r}.png" 9 9 FAST 0')
    nb = 2 if n == 15 else 1
    for i in range(nb):
        cw, ch = rep[f'boss{i}cell']; res.append(f'SPRITE l{n}_boss{i} "l{n}_boss{i}.png" {cw} {ch} FAST 0')
    if n == 1: wave = ['purple', 'purple', 'blue']; c = {}
    else:
        c = LJ[str(n)]; wave = c['sections'][0]['waves'][0]
    name = NAMES.get(n) or c['name']
    bosses = []
    for i in range(nb):
        key = 16 if (n == 15 and i == 1) else n
        if n == 1: bn, hp, mv, cool, sp = 'RAMROD', 30, ['charge', 'kick', 'fire'], 80, 1.0
        elif n == 15 and i == 0: bn, hp, mv, cool, sp = 'SHREDDER', 46, ['charge', 'kick'], 84, 1.15
        else:
            b = c['boss']; bn, hp, mv, cool, sp = b['name'], b['hp'], b['moves'], b.get('cool', 96), b.get('speed', 1) or 1
        cw, ch = rep[f'boss{i}cell']
        bosses.append(dict(name=bn, hp=round(hp * 1.5), fl=flags(mv), cool=cool, fast=1 if sp >= 1.2 else 0, spr=f'l{n}_boss{i}', cw=cw * 8, ch=ch * 8))
    zf = m['zf']; afs = m['afs']
    L.append(dict(n=n, name=name, wave=[ROLE[w] for w in wave][:6], zf=zf, afs=afs, na=na, bosses=bosses))
open(HERE + '/res/resources.res', 'w').write('\n'.join(res) + '\n')
h = ['// generated by gen_res.py - one LevelDef per level (data from the JS levels)', '#include "resources.h"']
h.append('typedef struct { const char* name; s16 hp; u8 fl, cool, fast, cw, ch; const SpriteDefinition* spr; } BossDef;')
h.append('typedef struct { const char* name; u8 nwave; u8 wave[6]; s16 zTop, zBot; u8 nArena; const Palette* zPal; const TileSet* zT; const MapDefinition* zM;')
h.append('  const Palette* aPal[2]; const TileSet* aT[2]; const MapDefinition* aM[2]; s16 aTop[2], aBot[2];')
h.append('  const SpriteDefinition* en[3]; u8 nBoss; BossDef boss[2]; } LevelDef;')
h.append('static const LevelDef LEVELS[15] = {')
for d in L:
    n = d['n']; w = d['wave'] + [0] * (6 - len(d['wave']))
    ap = ', '.join([f'&l{n}_ar{i}pal' for i in range(d['na'])] + ['NULL'] * (2 - d['na']))
    at = ', '.join([f'&l{n}_ar{i}t' for i in range(d['na'])] + ['NULL'] * (2 - d['na']))
    am = ', '.join([f'&l{n}_ar{i}m' for i in range(d['na'])] + ['NULL'] * (2 - d['na']))
    atop = ', '.join([str(a[0]) for a in d['afs']] + ['0'] * (2 - d['na'])); abot = ', '.join([str(min(a[1], 216)) for a in d['afs']] + ['0'] * (2 - d['na']))
    bs = ', '.join('{ "%s", %d, %d, %d, %d, %d, %d, &%s }' % (b['name'], b['hp'], b['fl'], b['cool'], b['fast'], b['cw'], b['ch'], b['spr']) for b in d['bosses'])
    if len(d['bosses']) == 1: bs += ', { 0 }'
    h.append(f'  {{ "{d["name"]}", {len(d["wave"])}, {{ {", ".join(map(str, w))} }}, {d["zf"][0]}, {min(d["zf"][1], 216)}, {d["na"]}, &l{n}_bgpal, &l{n}_bgt, &l{n}_bgm,')
    h.append(f'    {{ {ap} }}, {{ {at} }}, {{ {am} }}, {{ {atop} }}, {{ {abot} }},')
    h.append(f'    {{ &l{n}_light, &l{n}_weapon, &l{n}_big }}, {len(d["bosses"])}, {{ {bs} }} }},')
h.append('};')
open(HERE + '/src/levels_gen.h', 'w').write('\n'.join(h) + '\n')
for d in L: print(d['n'], d['name'], d['wave'], [(b['name'], b['hp'], b['fl'], b['cw'], b['ch']) for b in d['bosses']])
