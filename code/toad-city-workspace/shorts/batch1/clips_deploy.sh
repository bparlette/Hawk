#!/usr/bin/env bash
# clips_deploy.sh : ship the Shorts batch 1 "Clips" section to the LIVE home page only (game untouched) + commit to hark/integration.
# Pattern: gifs/deploy.sh. Stage = backup of live (so the live game.js and other builders' home work ship back byte-identical);
# mkclips.js inserts/replaces only the CLIPS:START/END block; media go to home/clips/. The lock is KEPT on success so the
# caller can push to bparlette/Hawk, then: rm /workspace/work/toad-city/locks/integration.lock
set -e
B=/workspace/work/toad-city/shorts/batch1; cd $B; TC=/workspace/work/toad-city; SRC=$TC/game-int; LOCK=$TC/locks/integration.lock
URL=https://toad-city-baltimore.surge.sh; mkdir -p logs
( set -o noclobber; echo "shorts-batch1 subagent: deploying home-page Clips (home/ only) $(date -u '+%F %T') UTC" > "$LOCK" ) 2>/dev/null || { echo "LOCK_BUSY: $(cat $LOCK)"; exit 3; }
trap 'rc=$?; if [ $rc -ne 0 ]; then rm -f "$LOCK"; echo "FAILED rc=$rc, lock released"; fi' EXIT
TS=$(date -u +%Y%m%dT%H%M); BK=$TC/live_backup_${TS}_pre_clips; mkdir -p "$BK/home"
get() { local code; code=$(curl -s -m 120 -o "$2" -w '%{http_code}' "$URL/$1?nc=$RANDOM"); [ "$code" = 200 ] || { echo "backup: $1 -> $code"; rm -f "$2"; return 1; }; }
for f in $(ls "$SRC/site"); do [ "$f" = home ] && continue; get "$f" "$BK/$f" || true; done
get home/index.html "$BK/home/index.html"
grep -oE '(src|href|poster|data-src)="[^"#?:]+"' "$BK/home/index.html" | sed -E 's/^[a-z-]+="//; s/"$//' | grep -vE '^(/|mailto)' | sort -u > tmp_refs.txt || true
while read -r r; do mkdir -p "$BK/home/$(dirname "$r")"; get "home/$r" "$BK/home/$r" || true; done < tmp_refs.txt
grep -oE "url\(['\"]?[^)'\":]+['\"]?\)" "$BK/home/index.html" | sed -E "s/^url\(['\"]?//; s/['\"]?\)$//" | sort -u > tmp_refs2.txt || true
while read -r r; do [ -f "$BK/home/$r" ] || { mkdir -p "$BK/home/$(dirname "$r")"; get "home/$r" "$BK/home/$r" || true; }; done < tmp_refs2.txt
for r in $(cd "$SRC/site/home" && find . -type f ! -path './gallery/*' ! -path './clips/*' | sed 's|^\./||'); do [ -f "$BK/home/$r" ] || { mkdir -p "$BK/home/$(dirname "$r")"; get "home/$r" "$BK/home/$r" || true; }; done
[ -s "$BK/game.js" ] && [ -s "$BK/index.html" ] || { echo "backup incomplete"; exit 1; }
MD5_BEFORE=$(md5sum < "$BK/game.js" | cut -c1-32)
echo "backup -> $BK ($(du -sh "$BK" | cut -f1)), live game.js md5 $MD5_BEFORE"
addclips() { # $1 = a home/ dir
  rm -rf "$1/clips"; mkdir -p "$1/clips"
  for n in $(node -e 'require("./clips_index.json").forEach(i=>console.log(i.name))'); do cp gifs/$n.gif gifs/$n.jpg final/$n.mp4 "$1/clips/"; done
  node mkclips.js "$1/index.html"
}
ST=$B/stage; rm -rf "$ST"; cp -a "$BK" "$ST"; addclips "$ST/home"
cmp -s "$ST/game.js" "$BK/game.js" || { echo "stage game.js changed?!"; exit 1; }
# only the CLIPS block differs between live and stage home/index.html
python3 - "$BK/home/index.html" "$ST/home/index.html" <<'EOF'
import re,sys
a,b=[open(p).read() for p in sys.argv[1:]]
strip=lambda s: re.sub(r'<!-- CLIPS:START[\s\S]*?<!-- CLIPS:END -->\n*\s*','',s)
print("home diff limited to CLIPS block" if strip(a)==strip(b) else "WARN: home diff outside CLIPS block")
EOF
# integration commit (home only)
addclips "$SRC/site/home"
git -C "$SRC" add site/home/clips site/home/index.html
git -C "$SRC" commit -q -m "home: Clips section (Shorts batch 1: 5 vertical 1080x1920 Shorts + looping GIF previews in home/clips/, generated by shorts/batch1/mkclips.js); home/ only, game untouched" && git -C "$SRC" log --oneline -1
export SURGE_TOKEN=$(cat /workspace/work/.surge_token) SURGE_LOGIN=rbparle@gmail.com
S=/workspace/work/trailer_v2/surge_cli/node_modules/.bin/surge
$S "$ST" toad-city-baltimore.surge.sh > logs/deploy.log 2>&1 && echo DEPLOY_OK || { echo DEPLOY_FAIL; tail -5 logs/deploy.log; exit 1; }
sleep 3
curl -s -m 60 -o tmp_live_game.js "$URL/game.js?nc=$RANDOM"; MD5_AFTER=$(md5sum < tmp_live_game.js | cut -c1-32)
echo "game.js md5 before=$MD5_BEFORE after=$MD5_AFTER $([ "$MD5_BEFORE" = "$MD5_AFTER" ] && echo MD5_SAME || echo MD5_CHANGED)"
echo "/ $(curl -s -o /dev/null -w '%{http_code}' $URL/)  /home/ $(curl -s -o tmp_live_home.html -w '%{http_code}' "$URL/home/?nc=$RANDOM")"
grep -q 'id="clips"' tmp_live_home.html && echo "clips section live" || { echo "clips MISSING on live /home/"; exit 1; }
bad=0; for f in $(ls "$ST/home/clips"); do c=$(curl -s -o /dev/null -w '%{http_code}' -I "$URL/home/clips/$f"); [ "$c" = 200 ] || { echo "media $f $c"; bad=1; }; done; [ $bad = 0 ] && echo "all clips media 200"
rm -f tmp_*.txt tmp_live_*
[ "$MD5_BEFORE" = "$MD5_AFTER" ] && echo DEPLOY_VERIFIED || exit 1
