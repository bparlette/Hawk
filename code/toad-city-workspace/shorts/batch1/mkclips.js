// mkclips.js <home/index.html> : insert (or replace) the home-page "Clips" section (Shorts batch 1).
// Idempotent: everything between <!-- CLIPS:START --> and <!-- CLIPS:END --> is regenerated. First time it is inserted
// just before the Gallery section (if present), else before the "coming" section, else before </main>.
// Own class prefix x-clip* and id "clips", so it never collides with the Gallery builder's section (id "gallery", x-gal*).
// Media live in home/clips/: <name>.gif (looping preview shown in the grid), <name>.mp4 (the full 1080x1920 Short).
const fs = require('fs'), path = require('path');
const file = process.argv[2]; if (!file) { console.error('usage: node mkclips.js <home/index.html>'); process.exit(2); }
const idx = JSON.parse(fs.readFileSync(path.join(__dirname, 'clips_index.json'), 'utf8'));
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const mb = (b) => (b / 1048576).toFixed(1) + ' MB';
let cards = '';
for (const it of idx) {
  cards += `
            <figure class="x-ink x-clip__card">
              <a class="x-clip__media" href="clips/${it.name}.mp4" target="_blank" rel="noopener" aria-label="Watch the ${esc(it.title)} Short (MP4)">
                <img src="clips/${it.name}.gif" alt="${esc(it.title)}: looping gameplay GIF" loading="lazy" width="${it.gw}" height="${it.gh}" />
                <span class="x-clip__play" aria-hidden="true">&#9654;</span>
              </a>
              <figcaption class="x-ink__body"><h4>${esc(it.title)}</h4><p class="sub">${esc(it.sub)}</p>
                <a class="x-clip__link" href="clips/${it.name}.mp4" target="_blank" rel="noopener">Watch the Short · ${Math.round(it.dur)} s · MP4 ${mb(it.mp4)}</a></figcaption>
            </figure>`;
}
const block = `<!-- CLIPS:START (generated by shorts/batch1/mkclips.js; do not hand-edit) -->
        <style>
          .x-clip__grid { display: grid; gap: 18px; grid-template-columns: repeat(auto-fill, minmax(min(100%, 200px), 1fr)); margin-top: 18px; }
          .x-clip__card { margin: 0; }
          .x-clip__media { position: relative; display: block; aspect-ratio: 9 / 16; background: var(--x-ink); border-bottom: 3px solid var(--x-line); overflow: hidden; }
          .x-clip__media img { display: block; width: 100%; height: 100%; object-fit: cover; }
          .x-clip__play { position: absolute; right: 10px; bottom: 10px; width: 40px; height: 40px; border-radius: 50%; display: grid; place-items: center; background: rgba(0,0,0,.62); color: #fff; font-size: 16px; padding-left: 3px; }
          .x-clip__card .x-ink__body { padding: 12px 16px 16px; gap: 4px; }
          .x-clip__card h4 { font-family: var(--x-display); font-weight: 400; font-size: clamp(20px, 4vw, 24px); letter-spacing: 0.04em; line-height: 1.05; margin: 0; }
          .x-clip__link { justify-self: start; margin-top: 6px; font: var(--type-small); color: var(--text-secondary); text-decoration: underline; text-underline-offset: 3px; }
        </style>
        <section class="section" id="clips" data-nav="Clips">
          <div class="head">
            <p class="head__eyebrow">Clips · vertical Shorts</p>
            <h2 class="x-h2">Clips</h2>
            <p class="head__sub">${idx.length} quick Shorts cut from real play, with the game's own music and sound. Tap one to watch the full clip.</p>
          </div>
          <div class="x-clip__grid">${cards}
          </div>
        </section>
        <!-- CLIPS:END -->`;
let html = fs.readFileSync(file, 'utf8');
const re = /<!-- CLIPS:START[\s\S]*?<!-- CLIPS:END -->/;
if (re.test(html)) html = html.replace(re, block);
else {
  let at = html.indexOf('<!-- GALLERY:START');
  if (at < 0) at = html.indexOf('<section class="section" id="coming"');
  if (at < 0) at = html.indexOf('</main>');
  if (at < 0) { console.error('no anchor for the clips section'); process.exit(1); }
  html = html.slice(0, at) + block + '\n\n        ' + html.slice(at);
}
fs.writeFileSync(file, html);
console.log('clips section:', idx.length, 'items ->', file);
