#!/usr/bin/env python3
# GR2 writing (Grok, Hawk branch claude/new-session-z5ikqq content/gr2_boss_writing.json): the Dragon Boat Duchess's boat_ambush lines
# -> src/06f0_gr2_duchess.js (adds GR1.bosses.dragon_boat_duchess.boat_ambush; her intro/defeat lines already ship in GR1).
# Usage: python3 writing/gen_gr2_duchess.py [path/to/gr2_boss_writing.json]
import json, sys, os
src = sys.argv[1] if len(sys.argv) > 1 else '/workspace/work/hawk-relay/content/gr2_boss_writing.json'
amb = json.load(open(src))['bosses']['dragon_boat_duchess']['boat_ambush']
js = ('// ---------------- GR2 writing (Grok, Hawk content/gr2_boss_writing.json): Dragon Boat Duchess boat_ambush lines; generated by writing/gen_gr2_duchess.py ----------------\n'
      'GR1.bosses.dragon_boat_duchess = Object.assign(GR1.bosses.dragon_boat_duchess || {}, { boat_ambush: ' + json.dumps(amb, ensure_ascii=False) + ' });\n')
p = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', '06f0_gr2_duchess.js')
open(p, 'w').write(js); print('wrote', os.path.normpath(p), len(js), 'bytes')
