#!/usr/bin/env python3
# writing/gen_gr1.py: writing/gr1_writing.json (Grok GR1 pack, hawk-relay content/gr1_writing.json with _canary + bump_410_canary already removed) -> src/06e_gr1_data.js (const GR1). Drops _canary and the bump_410_canary bumper.
import json, os
d = os.path.dirname(os.path.abspath(__file__))
w = json.load(open(os.path.join(d, 'gr1_writing.json')))
w.pop('_canary', None)
w['radio']['bumpers'] = [b for b in w['radio']['bumpers'] if 'canary' not in b['id']]
out = '// ---------------- GR1 writing pack (Grok): thug barks, boss lines, radio bumpers, landmark blurbs ----------------\n'
out += '// generated by writing/gen_gr1.py from writing/gr1_writing.json; edit the JSON and re-run, not this file\n'
out += 'const GR1 = ' + json.dumps(w, ensure_ascii=False, separators=(',', ':')) + ';\n'
open(os.path.join(d, '..', 'src', '06e_gr1_data.js'), 'w').write(out)
print('GR1 data', len(out), 'bytes; bumpers', [b['id'] for b in w['radio']['bumpers']])
