#!/usr/bin/env python3
# GR2 writing (Grok): copies the Chip Kid's intro/defeat lines and the new Harborplace blurb from Hawk content/gr2_boss_writing.json
# into src/06e_gr2_bosses.js (patches GR1 before 06f_barks wires boss lines + blurbs). Usage: python3 writing/gen_gr2.py [path/to/gr2_boss_writing.json]
import json, sys, os
src = sys.argv[1] if len(sys.argv) > 1 else '/workspace/work/hawk-relay/content/gr2_boss_writing.json'
d = json.load(open(src))
ck = d['bosses']['chip_kid']; hp = d['landmarks']['harborplace']
out = {'bosses': {'chip_kid': {'intro': ck['intro'], 'defeat': ck['defeat']}}, 'landmarks': {'harborplace': {'name': hp['name'], 'blurb': hp['blurb']}}}
js = ('// ---------------- GR2 writing pack (Grok, Hawk content/gr2_boss_writing.json): The Chip Kid lines + the new Harborplace blurb; generated by writing/gen_gr2.py ----------------\n'
      'const GR2 = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
      'Object.assign(GR1.bosses, GR2.bosses); Object.assign(GR1.landmarks, GR2.landmarks);\n')
p = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', '06e_gr2_bosses.js')
open(p, 'w').write(js); print('wrote', os.path.normpath(p), len(js), 'bytes')
